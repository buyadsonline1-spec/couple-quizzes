-- Пользователь попросил немного снизить шанс выпадения приза
-- "Романтический ужин «Вкусно и точка»" (категория 'dates', market
-- 'ru'). Весь бюджет вероятности категории 'dates' держится в сумме
-- весов её двух item'ов = 1 000 000 (см. комментарий в начале
-- wheel_reward_wheel.sql про "условные на реальный приз" веса) —
-- поэтому снятое с romantic-dinner отдаём единственному соседу по
-- категории (photoshoot), а не роняем в пустоту, иначе сумма весов
-- category перестанет соответствовать её документированной
-- абсолютной вероятности (124073 / 999999 от всех "настоящих призов").
--
-- 985075 -> 900000 (доля внутри категории 98.51% -> 90.00%,
-- абсолютная вероятность ~1 из 27 -> ~1 из 30 среди всех вращений).
-- photoshoot 14925 -> 100000, чтобы сумма весов категории не сдвинулась.
--
-- Применять в Supabase → SQL Editor, целиком, одним запуском.

update public.wheel_reward_items
   set weight = 900000
 where market = 'ru' and id = 'romantic-dinner';

update public.wheel_reward_items
   set weight = 100000
 where market = 'ru' and id = 'photoshoot';
