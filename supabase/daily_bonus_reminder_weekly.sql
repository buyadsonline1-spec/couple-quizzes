-- Перенастройка частоты рассылки-напоминания "забери дневной бонус"
-- (см. daily_bonus_reminder_cron.sql) с ежедневной на еженедельную —
-- по просьбе пользователя. Сам эндпоинт и его логика (кто ещё не
-- забрал бонус СЕГОДНЯ, на день самого запуска) не меняются — меняем
-- только расписание: вместо "каждый день в 17:00 UTC" теперь "каждый
-- понедельник в 17:00 UTC".
--
-- Применять в Supabase → SQL Editor, целиком, одним запуском.

select cron.alter_job(
  job_id := (select jobid from cron.job where jobname = 'daily-bonus-reminder'),
  schedule := '0 17 * * 1'
);
