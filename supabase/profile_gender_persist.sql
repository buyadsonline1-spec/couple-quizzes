-- profile.gender (пол для контента опросов/тестов "за парня"/"за
-- девушку") раньше жил ТОЛЬКО в localStorage клиента — сервер вообще
-- не знал о нём. На iOS (Capacitor, WKWebView на живом URL) каждая
-- переустановка тестового TestFlight-билда стирает localStorage, и
-- пользователь видит экран выбора пола заново при каждом заходе —
-- тот же класс бага, что уже чинили для дневного бонуса
-- (daily-bonus-state). Заодно из-за этого он мог не долистывать до
-- экранов, которые реально начисляют очки (опросы/тесты требуют
-- выбранный пол, см. app/page.tsx), что выглядело как "очки не
-- начисляются".
--
-- Применять в Supabase → SQL Editor, целиком, одним запуском.

alter table public.profiles
  add column if not exists gender text
    check (gender in ('boy', 'girl'));
